import os
import json
import openai
import pandas as pd
import random
from time import sleep
from tqdm import tqdm

openai.api_key = os.getenv("OPENAI_API_KEY", "key")

topic_list = [
    "Cooking", "Geography", "Astronomy", "Culture",
    "Technology", "Medicine", "Literature", "History",
    "Music", "Chemistry", "Biology", "Economy",
    "Mathematics", "Art", "Physics", "Science"
]
num_generic_samples = 1      # generic Q&A per topic
llm_model = "gpt-4"
rate_limit_seconds = 1.2     # seconds between calls

# adding reference
wikipedia_urls_by_topic = {
    "Cooking": ["https://ja.wikipedia.org/wiki/料理"],
    "Geography": ["https://ja.wikipedia.org/wiki/地理"],
    "Astronomy": ["https://ja.wikipedia.org/wiki/天文学"],
    "Culture": ["https://ja.wikipedia.org/wiki/文化"],
    "Technology": ["https://ja.wikipedia.org/wiki/技術"],
    "Medicine": ["https://ja.wikipedia.org/wiki/医学"],
    "Literature": ["https://ja.wikipedia.org/wiki/文学"],
    "History": ["https://ja.wikipedia.org/wiki/歴史"],
    "Music": ["https://ja.wikipedia.org/wiki/音楽"],
    "Chemistry": ["https://ja.wikipedia.org/wiki/化学"],
    "Biology": ["https://ja.wikipedia.org/wiki/生物学"],
    "Economy": ["https://ja.wikipedia.org/wiki/経済"],
    "Mathematics": ["https://ja.wikipedia.org/wiki/数学"],
    "Art": ["https://ja.wikipedia.org/wiki/芸術"],
    "Physics": ["https://ja.wikipedia.org/wiki/物理学"],
    "Science": ["https://ja.wikipedia.org/wiki/科学"],
}

# polishing functions by translating
def translate_japanese_to_english(text: str) -> str:
    response = openai.chat.completions.create(
        model=llm_model,
        messages=[
            {"role": "system", "content": "You are a professional translator. Translate the following Japanese text to English. Output only the translation."},
            {"role": "user",   "content": text}
        ],
        temperature=0.0,
        max_tokens=512
    )
    return response.choices[0].message.content.strip()


def translate_english_to_japanese(text: str) -> str:
    response = openai.chat.completions.create(
        model=llm_model,
        messages=[
            {"role": "system", "content": "You are a professional translator. Translate the following English text to Japanese. Output only the translation."},
            {"role": "user",   "content": text}
        ],
        temperature=0.0,
        max_tokens=512
    )
    return response.choices[0].message.content.strip()


def polish_japanese_text(text: str) -> str:
    response = openai.chat.completions.create(
        model=llm_model,
        messages=[
            {"role": "system", "content": "You are a Japanese text polisher. Refine the following Japanese text to be natural, concise, and clear."},
            {"role": "user",   "content": text}
        ],
        temperature=0.3,
        max_tokens=512
    )
    return response.choices[0].message.content.strip()

# generate prompt and json
def generate_json(prompt_header: str, count: int):
    system_message = (
        "You are a Japanese Q&A dataset generator.\n"
        "Please think step by step (chain of thought), showing your reasoning.\n"
        "When done, output exactly a JSON array of {count} objects.\n"
        "Each object should have keys exactly as specified in the header below.\n"
        "Use this separator:\n"
        "--- END OF REASONING, START JSON ---\n"
    ).replace("{count}", str(count))
    response = openai.chat.completions.create(
        model=llm_model,
        messages=[
            {"role": "system",  "content": system_message},
            {"role": "user",    "content": prompt_header}
        ],
        temperature=0.8,
        max_tokens=800
    )
    full_text = response.choices[0].message.content
    json_part = full_text.split('--- END OF REASONING, START JSON ---')[-1].strip()
    return json.loads(json_part)

# generating types
def create_generic_qas(topic: str, count: int):
    header_text = (
        f"Header schema: question, answer, topic\n"
        f"Topic: \"{topic}\"\n"
        f"Generate {count} generic Japanese Q&A pairs (JSON array)."
    )
    records = generate_json(header_text, count)
    for record in records:
        record["type"] = "generic"
    return records


def create_summarization_qas(topic: str):
    header_text = (
        "Header schema: question, answer, topic\n"
        f"Topic: \"{topic}\"\n"
        "Generate 1 summarization Q&A pair in Japanese:\n"
        "- Question should ask 'Summarize <topic> in two sentences.'\n"
        "- Answer should be the two‑sentence summary."
    )
    record = generate_json(header_text, 1)[0]
    record["type"] = "summarization"
    return [record]


def create_analysis_qas(topic: str):
    header_text = (
        "Header schema: question, answer, topic\n"
        f"Topic: \"{topic}\"\n"
        "Generate 1 analysis Q&A pair in Japanese:\n"
        "- Question should ask 'Analyze the importance or key aspects of <topic>.'\n"
        "- Answer should provide a concise analysis."
    )
    record = generate_json(header_text, 1)[0]
    record["type"] = "analysis"
    return [record]

# main function
def main():
    dataset_records = []
    for topic in tqdm(topic_list, desc="Topics processed"):
        generic_qas  = create_generic_qas(topic, num_generic_samples)
        summary_qas  = create_summarization_qas(topic)
        analysis_qas = create_analysis_qas(topic)

        urls = wikipedia_urls_by_topic.get(topic, [])
        for record in (generic_qas + summary_qas + analysis_qas):
            record["reference"] = random.choice(urls) if urls else ""

            question_english = translate_japanese_to_english(record["question"])
            question_back = translate_english_to_japanese(question_english)
            record["question_augmented"] = polish_japanese_text(question_back)

            answer_english = translate_japanese_to_english(record["answer"])
            answer_back = translate_english_to_japanese(answer_english)
            record["answer_augmented"] = polish_japanese_text(answer_back)

            record["topic"] = topic
            dataset_records.append(record)

        sleep(rate_limit_seconds)

    df = pd.DataFrame(
        dataset_records,
        columns=[
            "question", "answer",
            "question_augmented", "answer_augmented",
            "topic", "type", "reference"
        ]
    )
    df.to_csv("qa_dataset.csv", index=False, encoding="utf-8-sig")
    print(f"Saved {len(dataset_records)} samples")

if __name__ == "__main__":
    main()